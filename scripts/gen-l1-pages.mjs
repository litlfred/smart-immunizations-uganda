#!/usr/bin/env node
// The IG's two L1 pages, generated from the authored L1 and the scenario candidates:
//   input/pagecontent/l1-recommendations.md    every authored L1 statement, with its source
//   input/pagecontent/scenario-candidates.md   every L2 user-scenario candidate, with its statement
//
// Each statement links to the library entry it was read from (the published library page) and
// to the library section that holds its page or slide. Nothing is written by hand on these pages:
// change the L1 YAML or rerun l1-scenarios:uganda, then this script.
//
// Usage: node scripts/gen-l1-pages.mjs [--check]   (--check writes nothing; exit 1 when a page is stale)
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIR = "library/l1-recommendation-scenarios/uganda";
const SITE = "https://litlfred.github.io/smart-immunizations-uganda/en/cat-harness/library/smart-immunizations-uganda";
const REPO = "https://github.com/litlfred/smart-immunizations-uganda/blob/main";
const SOURCES = [
  { file: "ug-moh-schedule-poster.l1.yaml", candidates: "ug-moh-schedule-poster", label: "MoH schedule poster", unit: "page" },
  { file: "unepi-deck.l1.yaml", candidates: "unepi-deck", label: "UNEPI requirements deck", unit: "slide" },
];

const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");

/** The `{key: …}` rows of one top-level block of an authored L1 YAML (flow maps, one per line). */
export function rows(text, block) {
  const out = [];
  let inside = false;
  for (const line of text.split("\n")) {
    if (/^[a-z_]+:/.test(line)) inside = line.startsWith(`${block}:`);
    else if (inside && /^ {2}- \{/.test(line)) {
      const get = (k) => {
        const q = new RegExp(`\\b${k}:\\s*"((?:[^"\\\\]|\\\\.)*)"`).exec(line);
        if (q) return q[1].replace(/\\"/g, '"');
        const b = new RegExp(`\\b${k}:\\s*([^,}\\[]+)`).exec(line);
        return b ? b[1].trim() : undefined;
      };
      out.push({ key: get("key"), page: get("page"), image: get("image"), statement: get("statement"), name: get("name") });
    }
  }
  return out;
}

/** The source entry an authored L1 YAML names (`graph.source.entry`). */
export function entryOf(text) {
  const m = /^\s+entry:\s*(\S+)/m.exec(text);
  return m ? m[1].replace(/\/+$/, "").split("/").pop() : undefined;
}

/** The library section of `entry` whose page range holds `page`: {file, title}. */
function sectionFor(entry, page) {
  const dir = join("library", entry, "sections");
  const n = Number(page);
  // Ranges share their boundary page (a section ends on the slide the next one starts on), so the
  // section that STARTS latest at or before the page holds it.
  let best;
  for (const f of readdirSync(dir).filter((f) => f.endsWith(".md") && !f.startsWith("sec-front")).sort()) {
    const head = readFileSync(join(dir, f), "utf8").split("\n---")[0];
    const pages = /^pages:\s*(\d+)(?:-(\d+))?/m.exec(head);
    const title = /^section_title:\s*"?(.*?)"?\s*$/m.exec(head)?.[1] ?? f;
    if (!pages) continue;
    const from = Number(pages[1]);
    if (!(n >= from && n <= Number(pages[2] ?? pages[1]))) continue;
    if (best === undefined || from > best.from) best = { from, file: `library/${entry}/sections/${f}`, title, tie: false };
    else if (from === best.from) best.tie = true;
  }
  // Several sections on one page (a poster): no one of them holds the statement, so name none.
  return best && !best.tie ? { file: best.file, title: best.title } : undefined;
}

function build() {
  const rec = [];
  const scen = [];
  rec.push(
    "Every L1 statement this adaptation is built on, as authored in",
    `[\`${DIR}/\`](${REPO}/${DIR}/). Each is a verbatim quote of its source; the`,
    "source column links to the ingested source in the library and to the section",
    "that holds the page or slide. The same statements, with their WHO-vocabulary",
    "mapping and counts, are on the",
    "[L1 extraction viewer](https://litlfred.github.io/smart-immunizations-uganda/en/smart-base/l1-extraction/smart-immunizations-uganda/).",
    "",
    "*Generated by `scripts/gen-l1-pages.mjs`; do not edit.*",
    "",
  );
  scen.push(
    "The L2 user-scenario candidates derived from the [L1 recommendations](l1-recommendations.html),",
    "one per statement, by smart-base's `l1-recommendation-scenarios`",
    `(\`npm run l1-scenarios:uganda\`). They are **candidates**: an agent wrote them, and a`,
    "person reviews each before it becomes an L2 scenario.",
    "",
    "*Generated by `scripts/gen-l1-pages.mjs`; do not edit.*",
    "",
  );
  for (const s of SOURCES) {
    const text = readFileSync(join(DIR, s.file), "utf8");
    const entry = entryOf(text);
    const his = new Map(rows(text, "health_interventions").map((r) => [r.key, r.name]));
    const recs = rows(text, "recommendations").filter((r) => r.statement !== undefined);
    const byKey = new Map(recs.map((r) => [r.key, r]));
    rec.push(`### ${s.label} (${recs.length})`, "", `Source: [${entry}](${SITE}/${entry}/) in the library; authored in [\`${s.file}\`](${REPO}/${DIR}/${s.file}).`, "");
    rec.push("| key | statement | source |", "|---|---|---|");
    for (const r of recs) {
      const sec = r.page ? sectionFor(entry, r.page) : undefined;
      const where = r.page ? `${s.unit} ${r.page}` : "";
      const src = sec ? `[${cell(sec.title)}, ${where}](${REPO}/${sec.file})` : where;
      rec.push(`| ${r.key} | ${cell(r.statement)} | [${s.label}](${SITE}/${entry}/): ${src} |`);
    }
    rec.push("{:.grid}", "");
    if (his.size) rec.push(`Health interventions named: ${[...his.values()].map(cell).join("; ")}.`, "");

    const graph = JSON.parse(readFileSync(join(DIR, "candidates", s.candidates, "scenario-candidates.l2.json"), "utf8"));
    const us = graph.nodes.filter((n) => n.type === "user-scenario");
    const others = graph.nodes.filter((n) => n.type !== "user-scenario");
    scen.push(`### From the ${s.label} (${us.length})`, "");
    if (others.length) scen.push(`Personas and business processes: ${others.map((n) => `${cell(n.label)} (${n.type})`).join("; ")}.`, "");
    scen.push("| scenario | description | from statement |", "|---|---|---|");
    for (const n of us) {
      const key = /#([A-Za-z0-9_-]+)/.exec(n.evidence?.location ?? "")?.[1];
      const from = key && byKey.has(key) ? `[${key}](l1-recommendations.html): ${cell(byKey.get(key).statement)}` : cell(n.evidence?.location ?? "");
      scen.push(`| ${cell(n.properties?.id ?? n.label)} | ${cell(n.properties?.description ?? n.label)} | ${from} |`);
    }
    scen.push("{:.grid}", "");
  }
  return {
    "input/pagecontent/l1-recommendations.md": rec.join("\n"),
    "input/pagecontent/scenario-candidates.md": scen.join("\n"),
  };
}

function main() {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [p, body] of Object.entries(build())) {
    let now = "";
    try { now = readFileSync(p, "utf8"); } catch { /* missing */ }
    if (now === body) continue;
    if (check) { console.error(`✗ ${p} is stale: run node scripts/gen-l1-pages.mjs`); stale++; }
    else { writeFileSync(p, body); console.log(`wrote ${p}`); }
  }
  if (check && !stale) console.log("✓ L1 pages current");
  process.exit(stale ? 1 : 0);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
